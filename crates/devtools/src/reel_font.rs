pub fn draw_text(rgb: &mut [u8], width: usize, x: usize, y: usize, text: &str, color: [u8; 3], scale: usize) {
    let mut cursor = x;
    for ch in text.chars() {
        if let Some((_, rows)) = GLYPHS.iter().find(|(c, _)| *c == ch.to_ascii_lowercase()) {
            for (row, bits) in rows.iter().enumerate() {
                for col in 0..5 {
                    if bits >> (4 - col) & 1 == 1 {
                        for dy in 0..scale {
                            for dx in 0..scale {
                                let (px, py) = (cursor + col * scale + dx, y + row * scale + dy);
                                if px < width {
                                    if let Some(pixel) = rgb.get_mut((py * width + px) * 3..(py * width + px) * 3 + 3) {
                                        pixel.copy_from_slice(&color);
                                    }
                                }
                            }
                        }
                    }
                }
            }
        }
        cursor += 6 * scale;
    }
}
