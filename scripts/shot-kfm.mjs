import { createRequire } from 'module';
const { chromium } = createRequire(import.meta.url)('playwright');
const out = process.argv[2] || 'screenshots';
const base = process.argv[3] || 'http://localhost:5180/';
const b = await chromium.launch();
const p = await b.newPage({ viewport: { width: 1280, height: 720 } });
p.on('console', (m) => { if (m.type() === 'error' || m.type() === 'warning') console.log('console:', m.text()); });
p.on('pageerror', (e) => console.log('pageerror:', e.message));
await p.goto(base + '?screen=import');
await p.setInputFiles('input.f1', ['test-assets/kfm.zip', 'test-assets/stages.zip']);
await p.waitForTimeout(1500);
console.log(await p.locator('.log').innerText());
await p.screenshot({ path: `${out}/import.png` });
const ids = await p.evaluate(() => { const a = window.__ume; return { chars: a.reg.chars.map((c) => c.id), stages: a.reg.stages.map((s) => s.id) }; });
console.log(ids);
await p.evaluate(({ ids }) => {
  const a = window.__ume;
  a.mode = 'watch';
  a.sel.p1 = a.reg.chars[0]; a.sel.p2 = a.reg.chars[0];
  a.sel.stage = a.reg.stages.find((s) => s.kind === 'mugen' && s.name.includes('Training')) ?? a.reg.stages[0];
  a.startFight();
}, { ids });
await p.waitForTimeout(6000);
await p.screenshot({ path: `${out}/kfm-fight.png` });
await p.waitForTimeout(5000);
await p.screenshot({ path: `${out}/kfm-fight2.png` });
await b.close();
